#!/bin/sh
# Ключи и персональные данные в закоммиченных файлах. Совпадение - exit 1.
# Один сканер на репо: его зовёт tools/verify.sh, а значит и pre-push.
# Вызывать из корня репы: sh tools/scan-secrets.sh
#
# Правила - в tools/scan-secrets.py, по одному комментарию «почему» на каждое:
# (a) номер карты, проходящий Луна, кроме публичных тестовых;
# (b) IPv4 вне документационных сетей, 127/8, 0.0.0.0 и пула адресов движка;
# (c) метка PEM закрытого ключа где-либо, кроме tests/CaseRunner/GoldenKeys.cs;
# (d) поле ключа, секрета, токена или пароля со своим значением в tests/ и
#     integrations/ (в src/ и примере настроек - от восьми знаков) - только
#     ссылка $secret: или шаблон {…}; исключений по путям нет;
# (e) российский номер телефона в tests/, кроме нейтральных из GoldenInputs.
# Адрес и телефон, которые дословно стоят значением в определении
# integrations/*.json, - данные продукта: записанный
# провод их только повторяет, правила (b) и (e) их пропускают.
# Сканер печатает файл, строку и правило, но не найденное значение.
set -eu
cd "$(dirname "$0")/.."

python=$(command -v python3 || command -v python)
"$python" -I tools/scan-secrets.py
